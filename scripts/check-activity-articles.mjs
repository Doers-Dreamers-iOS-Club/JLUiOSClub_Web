import assert from 'node:assert/strict'
import { mkdir, readdir, readFile } from 'node:fs/promises'
import puppeteer from 'puppeteer-core'

const base = process.argv[2] || 'http://localhost:4175'
const output = '/private/tmp/club-activity-articles'
const root = new URL('../docs/activities/', import.meta.url)
const files = (await readdir(root, { recursive: true })).filter(file => file.endsWith('.md') && file !== 'AGENTS.md').sort()
const articles = []
for (const file of files) {
  const source = await readFile(new URL(file, root), 'utf8')
  if (source.includes('pageClass: mag-article-page')) articles.push({ file, route: '/activities/' + file.replace(/index\.md$|\.md$/g, '') })
}
await mkdir(output, { recursive: true })
const browser = await puppeteer.launch({ channel: 'chrome', headless: true })
try {
  const page = await browser.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'warn' && /Failed to resolve component/.test(message.text())) errors.push(message.text()) })
  page.on('response', response => { if (response.url().startsWith(base) && response.status() >= 400) errors.push(`${response.status()} ${response.url()}`) })
  await browser.defaultBrowserContext().overridePermissions(base, ['clipboard-read', 'clipboard-write', 'clipboard-sanitized-write'])
  for (const { file, route } of articles) {
    const name = file.replaceAll('/', '-').replace('.md', '')
    await page.setViewport({ width: 1440, height: 1000 })
    await page.goto(base + route, { waitUntil: 'networkidle0' })
    assert.equal(await page.$$eval('h1', elements => elements.length), 1, route)
    assert.equal(await page.$$eval('.mag-article', elements => elements.length), 1, route)
    assert.equal(await page.$$eval('.magazine-sidebar [aria-current="page"]', elements => elements.length), 1, route + ' current article in sidebar')
    assert.equal(await page.$eval('.VPSidebar', el => el.getBoundingClientRect().left >= 0), true, route + ' visible desktop sidebar')
    await page.waitForSelector('.VPLocalNavOutlineDropdown', { visible: true })
    assert.equal(await page.$$eval('.mag-article .mag-card, .mag-article .mag-step, .mag-article .mag-hero', elements => elements.length), 0, route)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false, route)
    assert.equal(await page.$$eval('.article-facts', blocks => blocks.some(el => /\*\*[^\n]+\*\*/.test(el.innerText))), false, 'No unparsed fact markup: ' + route)
    const toc = await page.$('.article-contents')
    if (toc) {
      await page.click('.article-contents summary')
      assert.equal(await page.$eval('.article-contents', el => el.open), true)
      assert.equal(await page.$$eval('.article-contents a', links => links.every(link => document.getElementById(decodeURIComponent(link.hash.slice(1))))), true, 'TOC targets: ' + route)
      await page.$eval('.article-contents a', el => el.click())
      await page.waitForFunction(() => location.hash && !document.documentElement.dataset.routeTransition)
      await new Promise(resolve => setTimeout(resolve, 700))
      await page.$eval('.article-contents', el => { el.open = false })
      await page.evaluate(() => scrollTo({ top: 0, behavior: 'instant' }))
    }
    const images = await page.$$('.mag-article__body img')
    if (images.length) {
      assert.equal(await page.$eval('.mag-article__body img', el => el.loading), 'eager', route)
      assert.equal(await page.$$eval('.mag-article__body img[decoding="async"]', elements => elements.every(el => el.hasAttribute('width') && el.hasAttribute('height'))), true, route)
      await page.$$eval('.mag-article__body img', images => Promise.all(images.map(image => { image.loading = 'eager'; return image.decode() })))
    }
    await page.screenshot({ path: `${output}/${name}-desktop.png` })
    await page.waitForSelector('.mag-article__outline-panel', { hidden: true })
    await page.click('.article-sidebar-toggle')
    await page.waitForFunction(() => !document.querySelector('.mag-article').style.transform)
    await page.waitForSelector('.mag-article__outline-panel', { hidden: true })
    assert.equal(await page.$eval('.mag-article__header', el => {
      const rect = el.getBoundingClientRect()
      return rect.width <= 1080 && Math.abs((rect.left + rect.right) / 2 - innerWidth / 2) < 1
    }), true, route + ' centered header retains margins')
    await page.$eval('.mag-article__body h2', el => el.scrollIntoView({ block: 'start', behavior: 'instant' }))
    await page.waitForSelector('.mag-article__outline-panel[data-state="visible"]', { visible: true })
    assert.equal(await page.$$eval('.mag-article__outline .outline-link', links => links.length > 0 && links.every(link =>
      document.getElementById(decodeURIComponent(link.hash.slice(1))) && getComputedStyle(link).opacity === '1')), true, route + ' populated outline with working targets')
    await page.screenshot({ path: `${output}/${name}-outline.png` })
    await page.$eval('.mag-article__outline .outline-link', el => el.click())
    await page.waitForFunction(() => location.hash && document.querySelector('.mag-article__outline .outline-link.active')?.hash === location.hash)
    await page.setViewport({ width: 1024, height: 844 })
    await page.waitForSelector('.VPLocalNavOutlineDropdown', { visible: true })
    await page.click('.VPLocalNavOutlineDropdown > button')
    await page.waitForSelector('.VPLocalNavOutlineDropdown .items', { visible: true })
    assert(await page.$('.VPLocalNavOutlineDropdown .outline-link'), route + ' narrow-screen outline')
    await page.keyboard.press('Escape')
    await page.setViewport({ width: 1440, height: 1000 })
    await page.click('.article-sidebar-toggle')
    await page.waitForSelector('.mag-article__outline-panel', { hidden: true })
    await page.waitForFunction(() => !document.querySelector('.mag-article').style.transform)
    if (images.length) {
      await page.$eval('.mag-article__body img', el => el.scrollIntoView({ block: 'center', behavior: 'instant' }))
      await page.screenshot({ path: `${output}/${name}-media.png` })
    }
    for (const width of [1280, 1024, 960, 390, 320]) {
      await page.setViewport({ width, height: 844 })
      await page.evaluate(width => { document.documentElement.classList.toggle('dark', width === 320); scrollTo({ top: 0, behavior: 'instant' }) }, width)
      await new Promise(resolve => setTimeout(resolve, 350))
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false, `${route} at ${width}px`)
      await page.screenshot({ path: `${output}/${name}-${width}.png` })
      if (width === 320 && images.length) {
        await page.$eval('.mag-article__body img', el => el.scrollIntoView({ block: 'center', behavior: 'instant' }))
        await page.screenshot({ path: `${output}/${name}-mobile-media.png` })
      }
    }
    await page.evaluate(() => document.documentElement.classList.remove('dark'))
    for (const href of await page.$$eval('.mag-article__footer a', links => links.map(link => link.href))) assert.equal((await fetch(href)).status, 200, href)
    console.log(`PASS ${route}: contextual outline, anchors, narrow-screen dropdown, layout, media, 1440/1280/1024/960/390/320px and dark mode`)
  }
  await page.setViewport({ width: 1440, height: 1000 })
  await page.goto(base + '/activities/261025-idea-workshop/', { waitUntil: 'networkidle0' })
  assert.equal(await page.$$eval('.contents-section:first-of-type .contents-entry', links => links.length), 3, 'Only three latest activities')
  const articleWidth = await page.$eval('.mag-article', el => el.getBoundingClientRect().width)
  await page.click('.article-sidebar-toggle')
  assert.equal(await page.$eval('.VPSidebar', el => el.inert), true, 'Closing sidebar removes focus targets immediately')
  assert.equal(await page.$eval('.article-sidebar-toggle', el => el.getAttribute('aria-label')), '展开栏目目录')
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.VPSidebar')).visibility === 'hidden')
  assert.equal(await page.$eval('.VPContent', el => getComputedStyle(el).paddingLeft), '0px', 'Collapsed article uses available width')
  assert(await page.$eval('.mag-article', (el, width) => el.getBoundingClientRect().width >= width, articleWidth))
  await page.keyboard.press('Enter')
  assert.equal(await page.$eval('.article-sidebar-toggle', el => el.getAttribute('aria-expanded')), 'true', 'Keyboard can reopen contents')
  assert.equal(await page.$eval('.VPSidebar', el => el.inert), false)
  assert.equal(await page.$eval('.contents-entry', el => getComputedStyle(el).animationName), 'contents-entry-in', 'Opening animates the entries')
  await page.waitForFunction(() => document.querySelector('.VPSidebar').getBoundingClientRect().left >= 0)
  const link = '.contents-entry[href="/activities/261016-huawei-ict/"]'
  const track = link + ' .roll-track'
  const rolled = () => page.$eval(track, el => new DOMMatrixReadOnly(getComputedStyle(el).transform).m42 < -10)
  await page.hover(link)
  await new Promise(resolve => setTimeout(resolve, 1100))
  assert(await rolled(), 'Homepage roll animation on hover')
  await page.mouse.move(800, 200)
  await new Promise(resolve => setTimeout(resolve, 1100))
  assert.equal(await rolled(), false, 'Roll returns on mouse leave')
  await page.focus(link)
  await new Promise(resolve => setTimeout(resolve, 1100))
  assert(await rolled(), 'Homepage roll animation on keyboard focus')
  await page.emulateMediaFeatures([{ name: 'prefers-reduced-motion', value: 'reduce' }])
  await page.$eval(link, el => el.blur())
  await page.hover(link)
  await new Promise(resolve => setTimeout(resolve, 100))
  assert(await rolled(), 'Reduced motion changes state without stagger')
  await page.click(link)
  await page.waitForFunction(() => document.querySelector('.contents-entry[aria-current="page"]')?.getAttribute('href') === '/activities/261016-huawei-ict/' && !document.documentElement.dataset.routeTransition)
  assert.equal(await page.$eval('.contents-entry[aria-current="page"]', el => el.getAttribute('href')), '/activities/261016-huawei-ict/')
  await page.setViewport({ width: 390, height: 844 })
  await new Promise(resolve => setTimeout(resolve, 350))
  assert.equal(await page.$eval('.VPLocalNav .menu-text', el => el.textContent.trim()), '栏目目录')
  assert.equal(await page.$eval('.VPLocalNavOutlineDropdown .menu-text', el => el.textContent.trim()), '本页目录')
  await page.click('.VPLocalNav .menu')
  await page.waitForSelector('.VPSidebar.open')
  await page.keyboard.press('Escape')
  assert.equal(await page.$('.VPSidebar.open'), null, 'Escape closes mobile contents')
  assert.equal(await page.$eval('.VPLocalNav .menu', el => el === document.activeElement), true, 'Escape restores trigger focus')
  await page.waitForFunction(() => document.querySelector('.VPSidebar').getBoundingClientRect().right <= 0)
  await page.waitForSelector('.VPBackdrop', { hidden: true })
  await page.click('.VPLocalNav .menu')
  await page.waitForFunction(() => document.querySelector('.VPSidebar.open')?.getBoundingClientRect().left >= 0)
  await page.click('.contents-entry[href="/activities/261011-autumn-welcome/"]')
  await page.waitForFunction(() => document.querySelector('.contents-entry[aria-current="page"]')?.getAttribute('href') === '/activities/261011-autumn-welcome/' && !document.documentElement.dataset.routeTransition)
  assert.equal(await page.$('.VPSidebar.open'), null, 'Article navigation closes mobile contents')
  await page.goto(base + '/about-us/maintenance/components', { waitUntil: 'networkidle0' })
  assert.equal(await page.$('.magazine-sidebar'), null, 'Other sections retain default sidebar')
  assert(await page.$('.VPSidebar .VPSidebarItem'), 'Default sidebar remains available')
  assert.equal(await page.$eval('.VPLocalNav .menu-text', el => el.textContent.trim()), '栏目目录', 'Non-course pages retain the general directory label')
  console.log('PASS magazine contents: hover, keyboard, reduced motion, active route, mobile drawer and other sections')
  await page.setViewport({ width: 390, height: 844 })
  await page.goto(base + '/activities/240407-maic-and-vision-pro/', { waitUntil: 'networkidle0' })
  await page.$eval('.mag-modal > button', button => button.click())
  await page.waitForSelector('dialog[open]')
  assert.equal(await page.$eval('dialog', el => el.scrollWidth > el.clientWidth + 1), false)
  await page.keyboard.press('Escape')
  assert.equal(await page.$eval('dialog', el => el.open), false)
  await page.goto(base + '/activities/260209-winter-swift/second', { waitUntil: 'networkidle0' })
  await page.$eval('.language-swift .copy', button => button.scrollIntoView({ block: 'center', behavior: 'instant' }))
  await page.click('.language-swift .copy')
  assert((await page.evaluate(() => navigator.clipboard.readText())).includes('struct Resolution'))
  const pre = await page.$eval('.language-swift pre', el => ({ scroll: el.scrollWidth, width: el.clientWidth }))
  assert(pre.scroll > pre.width, 'Long code remains horizontally scrollable')
  await page.$eval('.mag-article img', el => el.scrollIntoView({ block: 'center', behavior: 'instant' }))
  await page.click('.mag-article img')
  await page.waitForSelector('.medium-zoom-image--opened')
  await page.keyboard.press('Escape')
  await page.setJavaScriptEnabled(false)
  for (const { route } of articles) {
    await page.goto(base + route, { waitUntil: 'domcontentloaded' })
    assert(await page.$('.mag-article__body h2'), route + ' SSR sections')
    assert.equal(await page.$$eval('.magazine-sidebar [aria-current="page"]', elements => elements.length), 1, route + ' SSR navigation')
    assert.equal(await page.$eval('.mag-article__body', el => getComputedStyle(el).opacity), '1', route)
  }
  assert.deepEqual(errors, [])
  console.log(`PASS ${articles.length} articles without JavaScript; modal, code copy and scrolling, image zoom`)
  console.log(`Screenshots: ${output}`)
} finally { await browser.close() }
