import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import puppeteer from 'puppeteer-core'
const base = process.argv[2] || 'http://localhost:4173'
const out = 'output/design-contextual-demos-2026-11-02'
await fs.mkdir(out,{recursive:true})
const browser = await puppeteer.launch({channel:'chrome',headless:true})
const page = await browser.newPage()
await page.setViewport({width:1440,height:1000})
const errors=[]
page.on('pageerror',e=>errors.push(e.message))
async function open(chapter,selector){await page.goto(base+'/resources/ai-programming/chapters/'+chapter,{waitUntil:'networkidle0'});await page.$eval(selector,e=>e.scrollIntoView({block:'center',behavior:'instant'}))}
async function at(selector,frame){await page.waitForFunction(({selector,frame})=>Number(document.querySelector(selector).dataset.demoFrame)>=frame,{timeout:25000},{selector,frame})}
async function shot(selector,name){await (await page.$(selector)).screenshot({path:out+'/'+name+'.png'})}
try{
 await open('02','.context-desk')
 assert.equal(await page.$eval('.context-desk',e=>e.dataset.read),'false')
 assert.equal(await page.$$('.source-lines code').then(e=>e.length),0,'An unread path must not expose file contents')
 await at('.context-desk',11)
 assert.equal(await page.$eval('.context-desk',e=>e.dataset.read),'true')
 assert.equal(await page.$$('.source-lines code').then(e=>e.length),4)
 assert.equal(await page.$$('.context-note.visible').then(e=>e.length),3)
 await shot('.context-desk','context-complete')
 console.log('PASS file reading precedes concrete context')
 await open('04','.version-book')
 await at('.version-book',22)
 const stopped=await page.$eval('.version-book .demo-game',e=>e.dataset.position)
 await at('.version-book',24)
 assert.equal(await page.$eval('.version-book .demo-game',e=>e.dataset.position),stopped)
 assert.equal(await page.$eval('.version-book',e=>e.dataset.saved),'2')
 await shot('.version-book','version-saved')
 await at('.version-book',29)
 assert.equal(await page.$eval('.version-book',e=>e.dataset.version),'1')
 assert.equal(await page.$eval('.version-book',e=>e.dataset.saved),'2','Reviewing an older version must preserve newer history')
 assert.equal(await page.$eval('.version-book .demo-game',e=>e.dataset.paused),'false')
 await shot('.version-book','version-history')
 console.log('PASS pause freezes game, commits persist while reviewing older version')
 await open('05','.skill-recipe')
 const methods=await page.$$eval('.recipe-methods li',e=>e.map(x=>x.textContent.replace(/[✓0-9\s]/g,'')))
 await at('.skill-recipe',18)
 assert.equal(await page.$eval('.skill-recipe .demo-game',e=>e.dataset.kind),'bricks')
 assert.deepEqual(await page.$$eval('.recipe-methods li',e=>e.map(x=>x.textContent.replace(/[✓0-9\s]/g,''))),methods)
 await at('.skill-recipe',27)
 assert.equal(await page.$eval('.brick:nth-child(11)',e=>e.getAttribute('opacity')),'0','Collision removes the struck brick')
 await shot('.skill-recipe','skill-second-project')
 console.log('PASS same method transfers to another project with an actual collision')
 await open('06','.mcp-workbench')
 await at('.mcp-workbench',10)
 const moving=await page.$eval('.mcp-workbench .demo-game',e=>e.dataset.position)
 await at('.mcp-workbench',12)
 assert.notEqual(await page.$eval('.mcp-workbench .demo-game',e=>e.dataset.position),moving)
 await at('.mcp-workbench',14)
 const paused=await page.$eval('.mcp-workbench .demo-game',e=>e.dataset.position)
 await at('.mcp-workbench',18)
 assert.equal(await page.$eval('.mcp-workbench .demo-game',e=>e.dataset.position),paused)
 assert.equal(await page.$$('.tool-call.done').then(e=>e.length),4)
 assert(await page.$('.tool-receipt.received'))
 await shot('.mcp-workbench','mcp-returned')
 console.log('PASS browser opens, starts, pauses and returns observed result')
 await open('api-setup','.api-envelope')
 await at('.api-envelope',11)
 assert.equal(await page.$eval('.api-envelope',e=>e.dataset.chunks),'1')
 await at('.api-envelope',18)
 assert.equal(await page.$eval('.api-envelope',e=>e.dataset.chunks),'4')
 assert.equal(await page.$eval('.chat-answer > div',e=>e.textContent),'先读取当前项目，再添加轻松档。')
 await shot('.api-envelope','api-response')
 assert.deepEqual(errors,[])
 console.log('PASS response chunks arrive in order after request validation')
}finally{await browser.close()}
